CREATE OR ALTER FUNCTION viz.TicksTime(@DomainMin float,@DomainMax float,@TargetCount int)
RETURNS TABLE AS RETURN
WITH b AS (SELECT (CASE WHEN @DomainMin>=-3155673600000 AND @DomainMax<3187296000000 THEN @DomainMax-@DomainMin END)/NULLIF(CONVERT(bigint,@TargetCount)-1,0) Raw
 WHERE viz.EpochToTime(@DomainMin) IS NOT NULL AND viz.EpochToTime(@DomainMax) IS NOT NULL AND @DomainMin<@DomainMax AND @TargetCount BETWEEN 2 AND 12),
s AS (SELECT COALESCE((SELECT MIN(CONVERT(float,Ms)) FROM (VALUES(1000),(5000),(15000),(30000),(60000),(300000),(900000),(1800000),(3600000),(10800000),(21600000),(43200000),(86400000),(604800000)) c(Ms) WHERE Ms>=Raw),CEILING(Raw/604800000)*604800000) Step FROM b),
a AS (SELECT Step,CASE WHEN Step>=604800000 THEN CONVERT(float,172800000) ELSE 0 END Anchor FROM s),
t AS (SELECT (CEILING((@DomainMin-Anchor)/Step)+N)*Step+Anchor Value FROM a CROSS JOIN viz.Numbers(13)),
v AS (SELECT Value FROM t WHERE Value BETWEEN @DomainMin AND @DomainMax),
r AS (SELECT Value FROM v WHERE (SELECT COUNT(*) FROM v)>=2
 UNION ALL SELECT @DomainMin FROM b WHERE (SELECT COUNT(*) FROM v)<2
 UNION ALL SELECT @DomainMax FROM b WHERE (SELECT COUNT(*) FROM v)<2)
SELECT CONVERT(int,ROW_NUMBER() OVER(ORDER BY Value)-1) TickOrder,Value FROM r;
